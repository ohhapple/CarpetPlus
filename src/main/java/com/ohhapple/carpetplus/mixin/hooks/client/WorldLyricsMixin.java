package com.ohhapple.carpetplus.mixin.hooks.client;

import com.ohhapple.carpetplus.utils.music.MusicWorldLyricsRenderer;
import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.renderer.LevelRenderer;
import net.minecraft.client.renderer.SubmitNodeCollector;
import net.minecraft.client.renderer.state.level.LevelRenderState;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Environment(EnvType.CLIENT)
@Mixin(LevelRenderer.class)
public abstract class WorldLyricsMixin {
    @Inject(method = "submitFeatures", at = @At("TAIL"))
    private void carpetplus$submitWorldLyrics(LevelRenderState renderState,
                                               SubmitNodeCollector collector,
                                               boolean renderOutline,
                                               CallbackInfo callbackInfo) {
        MusicWorldLyricsRenderer.submit(collector);
    }
}
